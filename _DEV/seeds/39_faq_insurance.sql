-- 배경: 3차 수정으로 개인 보험 선택·수집을 폐지하고 참가자 전원 '스포츠안전재단 주최자배상책임보험' 적용.
--   FAQ 답변에 남은 '단체 상해보험(선택 희망 시 가입)·생년월일 입력' 안내를 클라이언트 확정 문구로 교체.
-- 영향: faqs 의 해당 질문 1행 content 만 갱신. 질문·순서·노출 여부 유지. 스키마 변경 없음. 멱등.
-- 같은 수정은 어드민 > FAQ 에서 직접 해도 된다(둘 중 하나만).
-- ============================================================
UPDATE faqs
SET content = '연수 기간 동안 스포츠안전재단 주최자배상책임보험에 가입되어 있습니다.

* 주최자배상책임보험은 개인 상해보험과 중복 보장이 되지 않습니다.
* 본 보험은 일정 중 ''리조트 내''에서 일어나는 사고에 대해 보장 적용 가능합니다.
* 기간 내 진료에 대한 이력이 있어야 보험 적용 가능함을 참고 부탁드립니다.'
WHERE question = '보험은 가입되나요?';

